@router.post("/translate_signwriting")
async def translate_signwriting(request: TextRequest):
    try:
        text = request.text.lower().strip()
        
        # Simple word-by-word translation
        words = text.split()
        signwriting_tokens = []
        
        for word in words:
            # Remove punctuation
            clean_word = ''.join(c for c in word if c.isalnum())
            if clean_word in SIGN_MAPPINGS:
                signwriting_tokens.append(SIGN_MAPPINGS[clean_word])
            else:
                # For unknown words, use a default sign
                signwriting_tokens.append("M530x540S1f720492x466S1f720492x466")
        
        # Join tokens with spaces
        fsw_result = " ".join(signwriting_tokens)
        
        return {
            "fsw": fsw_result,
            "tokens": signwriting_tokens,
            "original_text": request.text
        }
        
    except Exception as e:
        print(f"Translation error: {e}")
        raise HTTPException(status_code=500, detail=f"Translation failed: {str(e)}")
